using System.Globalization;
using LinguaFlow.Web;
using LinguaFlow.Web.Services;
using LinguaFlow.Core.Courses;
using LinguaFlow.Core.Progress;
using LinguaFlow.Core.Assessment;
using LinguaFlow.Core.Vocabulary;
using LinguaFlow.Core.Practice;
using LinguaFlow.Core.Analytics;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
using MudBlazor.Services;

var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
builder.Services.AddLocalization();
builder.Services.AddMudServices();
builder.Services.AddScoped<UiPreferences>();
builder.Services.AddScoped<CoursePathResolver>();
builder.Services.AddScoped<CourseContentValidator>();
builder.Services.AddScoped<CourseContentCache>();
builder.Services.AddScoped<CourseCatalogService>();
builder.Services.AddScoped<CourseManifestService>();
builder.Services.AddScoped<UnitContentService>();
builder.Services.AddScoped<LearningRepository>();
builder.Services.AddScoped<BackupValidator>();
builder.Services.AddScoped<CourseBackupService>();
builder.Services.AddScoped<AssessmentContentService>();
builder.Services.AddScoped<PracticeContentService>();
builder.Services.AddScoped<PracticeSessionService>();
builder.Services.AddScoped<PracticeFileService>();
builder.Services.AddScoped<PracticeResultValidator>();
builder.Services.AddScoped<PracticeResultService>();
builder.Services.AddScoped<LearningAnalyticsService>();
builder.Services.AddScoped<StudyActivityService>();
builder.Services.AddScoped<StudyTimerService>();
builder.Services.AddScoped<OfflineCourseService>();
builder.Services.AddScoped<ExerciseGradingService>();
builder.Services.AddScoped<ExerciseSessionService>();
builder.Services.AddScoped<UnitCompletionService>();
builder.Services.AddScoped<SpacedRepetitionService>();
builder.Services.AddScoped<VocabularyContentService>();
builder.Services.AddScoped<VocabularyLearningService>();
builder.Services.AddScoped<TextToSpeechService>();
builder.Services.AddScoped<ListeningEvidenceService>();
builder.Services.AddScoped<IReaderWorkspace, IndexedDbReaderWorkspace>();
builder.Services.AddScoped(sp => new HttpClient { BaseAddress = new Uri(builder.HostEnvironment.BaseAddress) });

var host = builder.Build();
var preferences = host.Services.GetRequiredService<UiPreferences>();
await preferences.InitializeAsync();
CultureInfo.DefaultThreadCurrentCulture = CultureInfo.GetCultureInfo(preferences.Language);
CultureInfo.DefaultThreadCurrentUICulture = CultureInfo.GetCultureInfo(preferences.Language);
await host.RunAsync();
